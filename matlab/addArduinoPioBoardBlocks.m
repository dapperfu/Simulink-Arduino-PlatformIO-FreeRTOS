function addArduinoPioBoardBlocks(libName)
%ADDARDUINOPIOBOARDBLOCKS - Fill board library folders with masked System blocks.
%   Replaces the former BoardStub placeholders. Each block is a masked subsystem
%   whose dialog promotes the MATLAB System properties and whose ports are fixed
%   to the data type the driver consumes. Called from createArduinoPioLibrary.
%
%   Syntax:
%       addArduinoPioBoardBlocks(libName)
%
%   Inputs:
%       libName - (1,1) string. Library model name, usually "arduinopio_lib".
%
%   Outputs:
%       none
%
%   Example:
%       addArduinoPioBoardBlocks("arduinopio_lib");
%
%   Other m-files required: none
%   Subfunctions: addUartPorts, addWifiBlocks, addBleBlocks, addDacBlock,
%       addNativeCanBlocks, addMaskedDriver
%   MAT-files required: none
%
%   See also: CREATEARDUINOPIOLIBRARY

%   Author: Frey, Jed
%   07-Oct-2026; Last revision: 07-Oct-2026

%------------- BEGIN CODE --------------
    arguments
        libName (1,1) string
    end

    mega = libName + "/Mega 2560";
    addUartPorts(mega, "mega2560", 1);
    addMaskedDriver(mega, "Mega Analog Input", "arduinopio.blocks.common.BoardAnalogInput", 7, ...
        MaskType="Arduino PIO Mega Analog Input", ...
        Description="Mega A0-A15 as channels 0-15. Output is uint16 ADC counts. Host simulation uses SimValue.", ...
        Settings=struct("Board", "mega2560", "Pin", "0", "SimValue", "0", "SampleTime", "-1"), ...
        Promote=["Board", "Pin", "SimValue", "SampleTime"], ...
        Prompts=["Board id", "Analog channel (0 = A0)", "Simulation output (uint16)", "Sample time (-1 = inherited)"], ...
        Outputs="Counts");
    addMaskedDriver(mega, "Mega PWM", "arduinopio.blocks.common.BoardPwm", 8, ...
        MaskType="Arduino PIO Mega PWM", ...
        Description="Mega PWM pins 2-13. Input is scalar uint8 duty, 0-255.", ...
        Settings=struct("Board", "mega2560", "Pin", "2", "SampleTime", "-1"), ...
        Promote=["Board", "Pin", "SampleTime"], ...
        Prompts=["Board id", "PWM pin", "Sample time (-1 = inherited)"], ...
        Inputs="Duty", InputTypes="uint8", InputDimensions="1");

    due = libName + "/Due";
    addDacBlock(due, "due", "66", "12", 1, ...
        "Due DAC0 is pin 66 and DAC1 is pin 67. Input is scalar uint16. ResolutionBits is 12.");
    addNativeCanBlocks(due, "arduinopio.blocks.common.NativeCanTransmit", ...
        "arduinopio.blocks.common.NativeCanReceive", "due", 2);
    addUartPorts(due, "due", 4);

    mkr = libName + "/MKR WiFi 1010";
    addDacBlock(mkr, "mkrWifi1010", "15", "10", 1, ...
        "MKR A0 is digital pin 15. Input is scalar uint16. DAC resolution is 10 bits.");
    addWifiBlocks(mkr, "arduinopio.blocks.mkr.WifiTransmit", "arduinopio.blocks.mkr.WifiReceive", 2);
    addBleBlocks(mkr, "arduinopio.blocks.common.ArduinoBleTransmit", ...
        "arduinopio.blocks.common.ArduinoBleReceive", 6);

    esp = libName + "/ESP32-WROOM";
    addDacBlock(esp, "esp32Wroom", "25", "8", 1, ...
        "ESP32 DAC GPIO 25 or 26. Input is scalar uint16 and the driver writes the low 8 bits.");
    addWifiBlocks(esp, "arduinopio.blocks.common.WifiTransmit", "arduinopio.blocks.common.WifiReceive", 2);
    addBleBlocks(esp, "arduinopio.blocks.common.BleTransmit", "arduinopio.blocks.common.BleReceive", 6);
    addMaskedDriver(esp, "Touch Read", "arduinopio.blocks.common.TouchRead", 8, ...
        MaskType="Arduino PIO Touch Read", ...
        Description="ESP32 touch GPIO. Output is scalar uint16. Host simulation uses SimValue.", ...
        Settings=struct("Board", "esp32Wroom", "Pin", "4", "SimValue", "0", "SampleTime", "-1"), ...
        Promote=["Board", "Pin", "SimValue", "SampleTime"], ...
        Prompts=["Board id", "Touch GPIO", "Simulation output (uint16)", "Sample time (-1 = inherited)"], ...
        Outputs="Value");

    r4 = libName + "/Uno R4";
    addDacBlock(r4, "unoR4", "14", "12", 1, ...
        "Uno R4 A0 is digital pin 14. Input is scalar uint16. ResolutionBits is 12.");
    addNativeCanBlocks(r4, "arduinopio.blocks.unoR4.NativeCanTransmit", ...
        "arduinopio.blocks.unoR4.NativeCanReceive", "unoR4", 2);
    addMaskedDriver(r4, "LED Matrix", "arduinopio.blocks.common.LedMatrixWrite", 4, ...
        MaskType="Arduino PIO LED Matrix", ...
        Description="Uno R4 WiFi 12x8 matrix. Input is uint8(12,1). Bit 0 of each column byte is row 0.", ...
        Settings=struct("SampleTime", "-1"), ...
        Promote="SampleTime", ...
        Prompts="Sample time (-1 = inherited)", ...
        Inputs="Columns", InputTypes="uint8", InputDimensions="[12, 1]");
    addWifiBlocks(r4, "arduinopio.blocks.unoR4.WifiTransmit", "arduinopio.blocks.unoR4.WifiReceive", 5);

    ble = libName + "/Nano 33 BLE";
    addMaskedDriver(ble, "PWM Analog Output", "arduinopio.blocks.common.BoardPwm", 1, ...
        MaskType="Arduino PIO PWM Analog Output", ...
        Description="Nano 33 BLE has no DAC. Input is scalar uint8 duty, 0-255, on a PWM pin.", ...
        Settings=struct("Board", "nano33Ble", "Pin", "3", "SampleTime", "-1"), ...
        Promote=["Board", "Pin", "SampleTime"], ...
        Prompts=["Board id", "PWM pin", "Sample time (-1 = inherited)"], ...
        Inputs="Duty", InputTypes="uint8", InputDimensions="1");
    addBleBlocks(ble, "arduinopio.blocks.common.ArduinoBleTransmit", ...
        "arduinopio.blocks.common.ArduinoBleReceive", 2);
end

function addUartPorts(parent, board, firstIndex)
%ADDUARTPORTS - Add Serial 1-3 transmit and receive masks for one board.
    port = 1;
    index = firstIndex;
    while port <= 3
        settings = struct("Board", board, "Port", string(port), "BaudRate", "115200", ...
            "DataLength", "1", "SampleTime", "-1");
        promote = ["Board", "Port", "BaudRate", "DataLength", "SampleTime"];
        prompts = ["Board id", "UART port (1=Serial1, 2=Serial2, 3=Serial3)", ...
            "Baud rate", "Bytes per step (uint8)", "Sample time (-1 = inherited)"];
        description = "Input or output data is uint8 of length DataLength. Status is logical.";
        addMaskedDriver(parent, "Serial " + string(port) + " Transmit", ...
            "arduinopio.blocks.common.UartTransmit", index, ...
            MaskType="Arduino PIO UART Transmit", Description=description, ...
            Settings=settings, Promote=promote, Prompts=prompts, ...
            Inputs="Data", InputTypes="uint8", InputDimensions="1");
        addMaskedDriver(parent, "Serial " + string(port) + " Receive", ...
            "arduinopio.blocks.common.UartReceive", index + 1, ...
            MaskType="Arduino PIO UART Receive", Description=description, ...
            Settings=settings, Promote=promote, Prompts=prompts, ...
            Outputs=["Data", "Status"]);
        port = port + 1;
        index = index + 2;
    end
end

function addDacBlock(parent, board, pin, bits, index, description)
%ADDDACBLOCK - Add a uint16 DAC write mask with a board-specific default pin.
    addMaskedDriver(parent, "DAC Write", "arduinopio.blocks.common.DacWrite", index, ...
        MaskType="Arduino PIO DAC Write", Description=description, ...
        Settings=struct("Board", board, "Pin", pin, "ResolutionBits", bits, "SampleTime", "-1"), ...
        Promote=["Board", "Pin", "ResolutionBits", "SampleTime"], ...
        Prompts=["Board id", "DAC pin", "Resolution (bits)", "Sample time (-1 = inherited)"], ...
        Inputs="Code", InputTypes="uint16", InputDimensions="1");
end

function addNativeCanBlocks(parent, transmitClass, receiveClass, board, firstIndex)
%ADDNATIVECANBLOCKS - Add onboard CAN transmit and receive masks.
    transmitSettings = struct("Board", board, "Controller", "0", "BaudRateKbps", "500", ...
        "MessageId", "256", "SampleTime", "-1");
    receiveSettings = struct("Board", board, "Controller", "0", "BaudRateKbps", "500", "SampleTime", "-1");
    addMaskedDriver(parent, "Onboard CAN Transmit", transmitClass, firstIndex, ...
        MaskType="Arduino PIO Onboard CAN Transmit", ...
        Description="Input is uint8(8,1). Due has controllers 0 and 1. Uno R4 has controller 0.", ...
        Settings=transmitSettings, ...
        Promote=["Board", "Controller", "BaudRateKbps", "MessageId", "ExtendedFrame", "RemoteFrame", "SampleTime"], ...
        Prompts=["Board id", "CAN controller", "Baud rate (kbps)", "Message id", ...
            "Extended frame", "Remote frame", "Sample time (-1 = inherited)"], ...
        Inputs="Data", InputTypes="uint8", InputDimensions="[8, 1]");
    addMaskedDriver(parent, "Onboard CAN Receive", receiveClass, firstIndex + 1, ...
        MaskType="Arduino PIO Onboard CAN Receive", ...
        Description="Outputs are uint32 Id, uint8(8,1) Data, uint8 Length, and logical Status.", ...
        Settings=receiveSettings, ...
        Promote=["Board", "Controller", "BaudRateKbps", "SampleTime"], ...
        Prompts=["Board id", "CAN controller", "Baud rate (kbps)", "Sample time (-1 = inherited)"], ...
        Outputs=["Id", "Data", "Length", "Status"]);
end

