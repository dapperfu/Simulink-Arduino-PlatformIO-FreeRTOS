        "RemoteHost", "192.168.1.20", "RemotePort", "5000", "DataLength", "1", "SampleTime", "-1");
    tcpTransmit = udpTransmit;
    tcpTransmit.Protocol = "TCP";
    udpReceive = struct("Protocol", "UDP", "Ssid", "arduino", "Password", "password", ...
        "RemoteHost", "192.168.1.20", "RemotePort", "5000", "LocalPort", "5000", ...
        "DataLength", "1", "SampleTime", "-1");
