    transmitPrompts = ["Protocol (UDP or TCP)", "SSID", "Password", "Remote host", ...
        "Remote port", "Bytes per step (uint8)", "Sample time (-1 = inherited)"];
    receivePromote = ["Protocol", "Ssid", "Password", "RemoteHost", "RemotePort", "LocalPort", "DataLength", "SampleTime"];
    receivePrompts = ["Protocol (UDP or TCP)", "SSID", "Password", "Remote host (TCP)", ...
        "Remote port (TCP)", "Local port (UDP)", "Bytes per step (uint8)", "Sample time (-1 = inherited)"];
    description = "Payload is uint8 of length DataLength. Receive status is logical and true when a byte arrives.";
    addMaskedDriver(parent, "WiFi UDP Transmit", transmitClass, firstIndex, ...
        MaskType="Arduino PIO WiFi UDP Transmit", Description=description, ...
