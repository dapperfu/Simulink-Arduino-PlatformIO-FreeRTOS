function addMaskedDriver(parent, name, className, index, options)
%ADDMASKEDDRIVER - Place a masked subsystem around one MATLAB System driver.
    arguments
        parent (1,1) string
        name (1,1) string
        className (1,1) string
        index (1,1) double {mustBeInteger, mustBePositive}
        options.MaskType (1,1) string
        options.Description (1,1) string
        options.Settings struct = struct()
        options.Promote (1,:) string = string.empty(1, 0)
        options.Prompts (1,:) string = string.empty(1, 0)
        options.Inputs (1,:) string = string.empty(1, 0)
        options.InputTypes (1,:) string = string.empty(1, 0)
        options.InputDimensions (1,:) string = string.empty(1, 0)
        options.Outputs (1,:) string = string.empty(1, 0)
    end

    if numel(options.Promote) ~= numel(options.Prompts)
        error("arduinopio:MaskPromptCount", ...
            "Block %s promote names and prompts must be the same length.", name);
    end

    dest = parent + "/" + name;
    col = mod(index - 1, 4);
    row = floor((index - 1) / 4);
    x = 40 + col * 160;
    y = 40 + row * 100;
    add_block("built-in/Subsystem", dest, Position=[x, y, x + 130, y + 70]);
    innerBlocks = find_system(dest, LookUnderMasks="all", SearchDepth=1, Type="Block");
    for innerIndex = 1:numel(innerBlocks)
        blockPath = string(innerBlocks{innerIndex});
        if blockPath ~= dest
            delete_block(blockPath);
        end
    end

    driver = dest + "/Driver";
    add_block("simulink/User-Defined Functions/MATLAB System", driver, ...
        Position=[140, 40, 300, 140]);
    set_param(driver, "System", className);
    settingNames = string(fieldnames(options.Settings));
    if ~isempty(settingNames)
        settingArgs = cell(1, 2 * numel(settingNames));
        for settingIndex = 1:numel(settingNames)
            settingName = settingNames(settingIndex);
            settingArgs{2 * settingIndex - 1} = char(settingName);
            settingArgs{2 * settingIndex} = char(options.Settings.(settingName));
        end
        set_param(driver, settingArgs{:});
    end

    for inputIndex = 1:numel(options.Inputs)
        inName = options.Inputs(inputIndex);
        add_block("simulink/Sources/In1", dest + "/" + inName, ...
            Position=[20, 30 + (inputIndex - 1) * 40, 50, 44 + (inputIndex - 1) * 40]);
        set_param(dest + "/" + inName, "OutDataTypeStr", options.InputTypes(inputIndex));
        set_param(dest + "/" + inName, "PortDimensions", options.InputDimensions(inputIndex));
        add_line(dest, inName + "/1", "Driver/" + string(inputIndex));
    end

    for outputIndex = 1:numel(options.Outputs)
        outName = options.Outputs(outputIndex);
        add_block("simulink/Sinks/Out1", dest + "/" + outName, ...
            Position=[360, 30 + (outputIndex - 1) * 40, 390, 44 + (outputIndex - 1) * 40]);
        add_line(dest, "Driver/" + string(outputIndex), outName + "/1");
    end

    if any(options.Promote == "Pin")
        displayCommand = arduinopio.maskDisplayWithPin(name);
    elseif any(options.Promote == "Port")
        displayCommand = arduinopio.maskDisplayWithPin(name, Expression="Port", Label="Port");
    elseif any(options.Promote == "Controller")
        displayCommand = arduinopio.maskDisplayWithPin(name, Expression="Controller", Label="CAN");
    else
        displayCommand = "disp('" + name + "')";
    end

    mask = Simulink.Mask.create(dest);
    mask.Type = options.MaskType;
    mask.Description = options.Description;
    mask.Display = displayCommand;
    for promoteIndex = 1:numel(options.Promote)
        propertyName = options.Promote(promoteIndex);
        mask.addParameter(Type="promote", TypeOptions={"Driver/" + propertyName}, ...
            Name=propertyName, Prompt=options.Prompts(promoteIndex));
    end
end
