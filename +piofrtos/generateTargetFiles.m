        "MODULES                 = |>MODEL_MODULES<|"
        "MAKEFILE                = |>MAKEFILE_NAME<|"
        "MATLAB_ROOT             = |>MATLAB_ROOT<|"
        "ALT_MATLAB_ROOT         = |>ALT_MATLAB_ROOT<|"
