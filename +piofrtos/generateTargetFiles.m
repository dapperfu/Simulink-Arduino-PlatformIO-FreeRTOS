        ""
        "firmware:"
        string(sprintf("\t""$(PIO_CMD)"" run --project-dir ."))
        string(sprintf("\t@echo ### Created PlatformIO firmware for $(MODEL)"))
        ""
        "upload:"
        string(sprintf("\t""$(PIO_CMD)"" run --project-dir . -t upload"))
        string(sprintf("\t@echo ### Uploaded PlatformIO firmware for $(MODEL)"))
        ""
        "else"
        ""
        ".PHONY: all"
        ""
