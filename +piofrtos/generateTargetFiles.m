function generatedFiles = generateTargetFiles(targetFolder)
%generateTargetFiles Write the system target file and template makefile.
%   generatedFiles = piofrtos.generateTargetFiles() writes piofrtos.tlc and
%   piofrtos.tmf into the target folder. Option names, defaults, and make
%   tokens come from piofrtos.getOptionTable so the two files stay aligned.
    arguments
        targetFolder (1,1) string = piofrtos.getTargetFolder()
    end

    if ~isfolder(targetFolder)
        mkdir(targetFolder);
    end

    tlcPath = fullfile(targetFolder, "piofrtos.tlc");
    tmfPath = fullfile(targetFolder, "piofrtos.tmf");
    writelines(buildSystemTargetFile(), tlcPath);
    writelines(buildTemplateMakefile(), tmfPath);

    generatedFiles = [tlcPath; tmfPath];
end

function lines = buildSystemTargetFile()
    optionTable = piofrtos.getOptionTable();
    lines = [
        "%% SYSTLC: Arduino FreeRTOS (PlatformIO) TMF: piofrtos.tmf MAKE: make_rtw"
        "%%"
        "%% Generated by piofrtos.generateTargetFiles. Do not edit by hand."
        "%% Abstract: Embedded Coder target that builds with host-installed PlatformIO"
        "%%           and maps each discrete sample rate to a FreeRTOS task."
        "%selectfile NULL_FILE"
        ""
        "%assign CodeFormat = ""Embedded-C"""
        "%assign TargetType = ""RT"""
        "%assign Language   = ""C"""
        "%assign PreCodeGenExecCompliant = 1"
        "%assign RateBasedStepFcn = 1"
        "%assign SuppressSetEventsForThisBaseRateFcn = 1"
        "%assign SuppressMultiTaskScheduler = 1"
        "%assign AutoBuildProcedure = TLC_FALSE"
        ""
        "%include ""codegenentry.tlc"""
        ""
        "/%"
        "  BEGIN_RTW_OPTIONS"
        ""
        "  oIdx = 1;"
        "  rtwoptions(oIdx).prompt         = 'PlatformIO';"
        "  rtwoptions(oIdx).type           = 'Category';"
        "  rtwoptions(oIdx).enable         = 'on';"
        string(sprintf("  rtwoptions(oIdx).default        = %d;", numel(optionTable)))
        "  rtwoptions(oIdx).popupstrings   = '';"
        "  rtwoptions(oIdx).tlcvariable    = '';"
        "  rtwoptions(oIdx).tooltip        = '';"
        "  rtwoptions(oIdx).callback       = '';"
        "  rtwoptions(oIdx).opencallback   = '';"
        "  rtwoptions(oIdx).closecallback  = '';"
        "  rtwoptions(oIdx).makevariable   = '';"
        ""
        ];

    for optionIndex = 1:numel(optionTable)
        option = optionTable(optionIndex);
        lines = [lines; buildRtwOptionBlock(option)]; %#ok<AGROW>
    end

    lines = [lines;
        "  rtwgensettings.BuildDirSuffix = '_piofrtos_rtw';"
        "  rtwgensettings.Version        = '1';"
        "  rtwgensettings.DerivedFrom    = 'ert.tlc';"
        "  rtwgensettings.SelectCallback = 'piofrtos.selectCallback(hDlg, hSrc)';"
        ""
        "  END_RTW_OPTIONS"
        "%/"
        ];
end

function lines = buildRtwOptionBlock(option)
    tooltipLiteral = toMatlabSingleQuoted(option.Tooltip);
    defaultLiteral = toMatlabSingleQuoted(option.Default);
    popupLiteral = toMatlabSingleQuoted(getOptionField(option, "PopupStrings", ""));
    callbackLiteral = toMatlabSingleQuoted(getOptionField(option, "Callback", ""));

    lines = [
        "  oIdx = oIdx + 1;"
        string(sprintf("  rtwoptions(oIdx).prompt         = '%s';", option.Prompt))
        string(sprintf("  rtwoptions(oIdx).type           = '%s';", option.Type))
        "  rtwoptions(oIdx).enable         = 'on';"
        string(sprintf("  rtwoptions(oIdx).default        = %s;", defaultLiteral))
        string(sprintf("  rtwoptions(oIdx).popupstrings   = %s;", popupLiteral))
        string(sprintf("  rtwoptions(oIdx).tlcvariable    = '%s';", option.TlcVariable))
        string(sprintf("  rtwoptions(oIdx).makevariable   = '%s';", option.MakeVariable))
        string(sprintf("  rtwoptions(oIdx).tooltip        = %s;", tooltipLiteral))
        string(sprintf("  rtwoptions(oIdx).callback       = %s;", callbackLiteral))
        ""
        ];
end

function value = getOptionField(option, fieldName, defaultValue)
    if isfield(option, fieldName)
        value = option.(fieldName);
    else
        value = defaultValue;
    end
end

function literal = toMatlabSingleQuoted(value)
    escaped = replace(string(value), "'", "''");
    literal = "'" + escaped + "'";
end

function lines = buildTemplateMakefile()
